"""Enumeration of SOC types used in the benchmark."""

from __future__ import annotations

from enum import Enum


class SOCType(str, Enum):
    """Type of SOC estimate stored in the COLUMNS.SOC column."""

    MEASURED_REFERENCE = "measured_reference"
    """Directly measured by calibrated equipment (most accurate)."""

    CYCLER_REFERENCE = "cycler_reference"
    """Reported by the battery cycler software."""

    COULOMB_COUNTED_FIXED_CAPACITY = "coulomb_counted_fixed_capacity"
    """Computed via coulomb counting using a fixed nominal capacity."""

    COULOMB_COUNTED_DYNAMIC_CAPACITY = "coulomb_counted_dynamic_capacity"
    """Computed via coulomb counting with capacity estimated per cycle."""

    PSEUDO_LABEL = "pseudo_label"
    """Generated by another model; not to be treated as ground truth."""

    UNAVAILABLE = "unavailable"
    """SOC labels are not available for this domain."""
